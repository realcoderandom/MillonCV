import { readFile } from 'node:fs/promises'
import { test, expect, openResume, readStoredState, resumeFixture, seedStorage, storedFixture, storedJson, STORAGE_KEY, switchMode } from '@/../tests/e2e/fixtures'

test('模块、源码与富文本切换均保留末次输入', async ({ page }) => {
  await seedStorage(page)
  await openResume(page)
  await page.getByRole('textbox', { name: '姓名', exact: true }).fill('模块末次输入')
  await switchMode(page, 'Markdown')
  const source = page.getByRole('textbox', { name: 'Markdown 简历源码' })
  await expect(source).toHaveValue(/^# 模块末次输入\n/)
  await source.fill((await source.inputValue()).replace('# 模块末次输入', '# 源码末次输入'))
  await switchMode(page, '文档编辑')
  const heading = page.getByRole('textbox', { name: '富文本简历编辑器' }).locator('h1')
  await expect(heading).toHaveText('源码末次输入')
  await heading.fill('富文本末次输入')
  await switchMode(page, '模块编辑')
  await expect(page.getByRole('textbox', { name: '姓名', exact: true })).toHaveValue('富文本末次输入')
  await page.reload()
  await expect(page.getByRole('textbox', { name: '姓名', exact: true })).toHaveValue('富文本末次输入')
})

for (const mode of ['模块编辑', 'Markdown', '文档编辑'] as const) {
  test(`${mode} 输入后立即刷新保留最后一次修改`, async ({ page }) => {
    await page.clock.install()
    await seedStorage(page)
    await openResume(page)
    if (mode !== '模块编辑') await switchMode(page, mode)
    await page.clock.pauseAt(await page.evaluate(() => Date.now() + 1000))
    if (mode === '模块编辑') await page.getByRole('textbox', { name: '姓名', exact: true }).fill('刷新前末次输入')
    else if (mode === 'Markdown') {
      const source = page.getByRole('textbox', { name: 'Markdown 简历源码' })
      await source.fill((await source.inputValue()).replace('# 当前姓名', '# 刷新前末次输入'))
    } else await page.getByRole('textbox', { name: '富文本简历编辑器' }).locator('h1').fill('刷新前末次输入')
    await page.reload()
    await page.clock.resume()
    await expect(page.getByRole('textbox', { name: '姓名', exact: true })).toHaveValue('刷新前末次输入')
  })
}

